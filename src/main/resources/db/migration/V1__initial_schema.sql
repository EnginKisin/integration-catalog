CREATE TABLE user_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),
    username VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    email VARCHAR(254),
    email_verified BOOLEAN DEFAULT FALSE NOT NULL,
    active BOOLEAN DEFAULT TRUE NOT NULL,
    password_reset_required BOOLEAN DEFAULT FALSE NOT NULL,
    session_version BIGINT DEFAULT 0 NOT NULL,
    version BIGINT DEFAULT 0,
    role VARCHAR(255) NOT NULL,
    CONSTRAINT uk_user_accounts_username UNIQUE (username),
    CONSTRAINT uk_user_accounts_email UNIQUE (email),
    CONSTRAINT ck_user_accounts_role CHECK (role IN ('ADMIN', 'EDITOR', 'VIEWER'))
);

CREATE TABLE user_permissions (
    user_id BIGINT NOT NULL,
    permission VARCHAR(255) NOT NULL,
    CONSTRAINT uk_user_permissions UNIQUE (user_id, permission),
    CONSTRAINT fk_user_permissions_account FOREIGN KEY (user_id) REFERENCES user_accounts (id),
    CONSTRAINT ck_user_permissions_permission CHECK (permission IN ('VIEW_CREDENTIALS', 'MANAGE_CREDENTIALS'))
);

CREATE TABLE account_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    purpose VARCHAR(255) NOT NULL,
    email VARCHAR(254) NOT NULL,
    session_version BIGINT NOT NULL,
    issued_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_account_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_account_tokens_account FOREIGN KEY (account_id) REFERENCES user_accounts (id),
    CONSTRAINT ck_account_tokens_purpose CHECK (purpose IN ('INVITATION', 'PASSWORD_RESET', 'EMAIL_CHANGE'))
);

CREATE INDEX idx_account_tokens_account_purpose ON account_tokens (account_id, purpose);

CREATE TABLE account_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(255) NOT NULL,
    account_id BIGINT NOT NULL,
    action VARCHAR(255) NOT NULL,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE mail_outbox (
    id UUID PRIMARY KEY,
    encrypted_payload JSONB,
    next_attempt_at TIMESTAMP(6) WITH TIME ZONE,
    sent_at TIMESTAMP(6) WITH TIME ZONE,
    failed_at TIMESTAMP(6) WITH TIME ZONE,
    attempts INTEGER NOT NULL
);

CREATE INDEX idx_mail_outbox_delivery ON mail_outbox (sent_at, failed_at, next_attempt_at);

CREATE TABLE systems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active BOOLEAN DEFAULT TRUE NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500) NOT NULL
);

CREATE TABLE integrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),
    version BIGINT DEFAULT 0,
    review_required BOOLEAN DEFAULT FALSE NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500) NOT NULL,
    source_system_id BIGINT NOT NULL,
    destination_system_id BIGINT NOT NULL,
    has_middleware BOOLEAN NOT NULL,
    middleware_system_id BIGINT,
    source_payload_format VARCHAR(255) NOT NULL,
    destination_payload_format VARCHAR(255) NOT NULL,
    is_sync BOOLEAN NOT NULL,
    status VARCHAR(255) NOT NULL,
    CONSTRAINT fk_integrations_source FOREIGN KEY (source_system_id) REFERENCES systems (id),
    CONSTRAINT fk_integrations_destination FOREIGN KEY (destination_system_id) REFERENCES systems (id),
    CONSTRAINT fk_integrations_middleware FOREIGN KEY (middleware_system_id) REFERENCES systems (id),
    CONSTRAINT ck_integrations_source_format CHECK (source_payload_format IN ('JSON', 'XML', 'IDOC', 'CSV', 'EXCEL')),
    CONSTRAINT ck_integrations_destination_format CHECK (destination_payload_format IN ('JSON', 'XML', 'IDOC', 'CSV', 'EXCEL')),
    CONSTRAINT ck_integrations_status CHECK (status IN ('DRAFT', 'COMPLETED'))
);

CREATE TABLE environment_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),
    integration_id BIGINT NOT NULL,
    config_target VARCHAR(255) NOT NULL,
    environment_type VARCHAR(255) NOT NULL,
    url VARCHAR(100) NOT NULL,
    timeout_ms INTEGER,
    auth_type VARCHAR(255) NOT NULL,
    auth_credentials JSONB,
    retry_count INTEGER,
    retry_interval_ms INTEGER,
    CONSTRAINT fk_environment_configs_integration FOREIGN KEY (integration_id) REFERENCES integrations (id),
    CONSTRAINT ck_environment_configs_target CHECK (config_target IN ('DESTINATION', 'MIDDLEWARE')),
    CONSTRAINT ck_environment_configs_environment CHECK (environment_type IN ('DEV', 'TEST', 'PROD')),
    CONSTRAINT ck_environment_configs_auth CHECK (auth_type IN ('NONE', 'BASIC_AUTH', 'OAUTH2', 'API_KEY'))
);

CREATE TABLE mapping_schemas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),
    integration_id BIGINT NOT NULL,
    schema_type VARCHAR(255) NOT NULL,
    schema_definition JSONB NOT NULL,
    sample_payload JSONB,
    target_schema_definition JSONB,
    target_sample_payload JSONB,
    target_format VARCHAR(16),
    target_raw_content TEXT,
    format VARCHAR(16) DEFAULT 'JSON' NOT NULL,
    raw_content TEXT,
    file_name VARCHAR(255),
    content_type VARCHAR(255),
    sample_file BYTEA,
    csv_delimiter VARCHAR(255),
    csv_has_header BOOLEAN,
    CONSTRAINT fk_mapping_schemas_integration FOREIGN KEY (integration_id) REFERENCES integrations (id),
    CONSTRAINT ck_mapping_schemas_type CHECK (schema_type IN (
        'SOURCE_TO_MW_REQUEST', 'MW_TO_DEST_REQUEST', 'DEST_TO_MW_RESPONSE',
        'MW_TO_SOURCE_RESPONSE', 'SOURCE_TO_DEST_REQUEST', 'DEST_TO_SOURCE_RESPONSE'
    )),
    CONSTRAINT ck_mapping_schemas_format CHECK (format IN ('JSON', 'XML', 'IDOC', 'CSV', 'EXCEL')),
    CONSTRAINT ck_mapping_schemas_target_format CHECK (target_format IN ('JSON', 'XML', 'IDOC', 'CSV', 'EXCEL'))
);

CREATE TABLE field_mappings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),
    integration_id BIGINT NOT NULL,
    source_schema_id BIGINT NOT NULL,
    source_field_path VARCHAR(500) NOT NULL,
    target_schema_id BIGINT NOT NULL,
    target_field_path VARCHAR(500) NOT NULL,
    is_ai_generated BOOLEAN NOT NULL,
    ai_confidence_score DOUBLE PRECISION,
    origin VARCHAR(24),
    ai_job_id VARCHAR(36),
    ai_suggestion_id VARCHAR(40),
    CONSTRAINT fk_field_mappings_integration FOREIGN KEY (integration_id) REFERENCES integrations (id),
    CONSTRAINT fk_field_mappings_source_schema FOREIGN KEY (source_schema_id) REFERENCES mapping_schemas (id),
    CONSTRAINT fk_field_mappings_target_schema FOREIGN KEY (target_schema_id) REFERENCES mapping_schemas (id)
);

CREATE TABLE ai_mapping_jobs (
    id VARCHAR(36) PRIMARY KEY,
    integration_id BIGINT NOT NULL,
    created_by VARCHAR(254) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    context_revision VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    provider VARCHAR(40) NOT NULL,
    model VARCHAR(150) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    lease_until TIMESTAMP(6) WITH TIME ZONE,
    input_snapshot JSONB,
    result JSONB,
    error_code VARCHAR(64),
    error_message VARCHAR(500),
    CONSTRAINT uk_ai_mapping_job_idempotency UNIQUE (integration_id, created_by, idempotency_key),
    CONSTRAINT fk_ai_mapping_jobs_integration FOREIGN KEY (integration_id) REFERENCES integrations (id) ON DELETE CASCADE
);

CREATE INDEX ai_mapping_jobs_queue_idx ON ai_mapping_jobs (status, created_at);

CREATE TABLE mapping_append_receipts (
    id VARCHAR(36) PRIMARY KEY,
    integration_id BIGINT NOT NULL,
    created_by VARCHAR(254) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    response JSONB NOT NULL,
    CONSTRAINT uk_mapping_append_receipt_idempotency UNIQUE (integration_id, created_by, idempotency_key),
    CONSTRAINT fk_mapping_append_receipts_integration FOREIGN KEY (integration_id) REFERENCES integrations (id) ON DELETE CASCADE
);
